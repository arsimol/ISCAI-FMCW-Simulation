% =========================================================================
% Φάση 1: Προσομοίωση Καθαρού FMCW Radar (Μέτρηση Απόστασης)
% =========================================================================
clear; clc; close all;

%% 1. Παράμετροι Συστήματος (Προσαρμοσμένες για οπτικοποίηση)
c = 3e8;            % Ταχύτητα του φωτός (m/s)
B = 150e6;          % Εύρος ζώνης (Bandwidth) - 150 MHz
T = 10e-6;          % Διάρκεια ενός chirp (10 microseconds)
mu = B / T;         % Κλίση συχνότητας (Chirp slope)
fc = 24e9;          % Φέρουσα συχνότητα (24 GHz - τυπική για ραντάρ)

fs = 4 * B;         % Συχνότητα δειγματοληψίας (Nyquist)
t = 0:1/fs:T-1/fs;  % Διάνυσμα χρόνου για ένα chirp
N = length(t);      % Αριθμός δειγμάτων

%% 2. Ορισμός Στόχου
target_range = 50;  % Απόσταση στόχου (50 μέτρα)
target_vel = 0;     % Ταχύτητα στόχου (την κρατάμε 0 για τώρα)

% Υπολογισμός χρονικής καθυστέρησης (πήγαινε-έλα του φωτός)
tau = 2 * target_range / c; 

%% 3. Δημιουργία Σημάτων (Βάσει των εξισώσεων της εργασίας)
A_T = 1; % Πλάτος εκπομπής
A_R = 0.1; % Πλάτος λήψης (η ηχώ είναι πάντα πιο αδύναμη)

% Α. Τοπικός Ταλαντωτής (LO) - Εκπεμπόμενο Σήμα
% Τύπος: s_LO(t) = A_T * exp(j * (2*pi*fc*t + pi*mu*t^2))
s_LO = A_T * exp(1j * (2*pi*fc*t + pi*mu.*t.^2));

% Β. Λαμβανόμενο Σήμα (RX) - Η ηχώ με την καθυστέρηση tau
s_RX = A_R * exp(1j * (2*pi*fc*(t-tau) + pi*mu.*(t-tau).^2));

%% 4. Μίξη Σημάτων (Dechirping) για εξαγωγή του IF
% Πολλαπλασιάζουμε το LO με το συζυγές του RX για να βγει θετική συχνότητα!
s_IF = s_LO .* conj(s_RX);

%% 5. Επεξεργασία Σήματος (1D FFT για εύρεση απόστασης)
% Κάνουμε FFT στο σήμα IF
fft_IF = fft(s_IF);
fft_IF = abs(fft_IF(1:N/2)); % Κρατάμε το θετικό μισό των συχνοτήτων

% Μετατροπή του άξονα x από Συχνότητες (Hz) σε Απόσταση (Μέτρα)
frequencies = (0:N/2-1) * (fs/N);
range_axis = (frequencies * c) / (2 * mu);

%% 6. Οπτικοποίηση (Διαγράμματα)
figure('Name', 'Φάση 1: Καθαρό FMCW Radar', 'Position', [100, 100, 800, 500]);

% Διάγραμμα 1: Το σήμα IF στον χρόνο
subplot(2,1,1);
plot(t*1e6, real(s_IF), 'b');
title('Το Σήμα IF (Ενδιάμεσης Συχνότητας) στον Χρόνο');
xlabel('Χρόνος (\mus)'); ylabel('Πλάτος'); grid on;

% Διάγραμμα 2: Το προφίλ απόστασης (Το αποτέλεσμα του FFT)
subplot(2,1,2);
plot(range_axis, fft_IF, 'r', 'LineWidth', 2);
title('Προφίλ Απόστασης (Μετασχηματισμός Fourier 1D)');
xlabel('Απόσταση (Μέτρα)'); ylabel('Ισχύς Ανακλάσης'); 
xlim([0 100]); grid on;

% Βρίσκουμε αυτόματα πού είναι η κορυφή
[~, max_idx] = max(fft_IF);
detected_range = range_axis(max_idx);
hold on; plot(detected_range, fft_IF(max_idx), 'ko', 'MarkerSize', 8, 'LineWidth', 2);
legend('Σήμα Ραντάρ', sprintf('Εντοπισμός Στόχου: %.2f m', detected_range));